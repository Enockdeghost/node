//declaration and initialization of variables

// In JavaScript, you can declare a variable using the var, let, or const keywords. When you declare a variable, you can also initialize it by assigning it a value at the same time.

// Example of variable declaration and initialization
var name = "John"; // declaring and initializing a variable with var
let age = 30; // declaring and initializing a variable with let
const PI = 3.14; // declaring and initializing a constant variable with const

// You can also declare a variable without initializing it, and then assign it a value later in the code.

var city; // declaring a variable without initializing it
city = "New York"; // assigning a value to the variable later in the code

// However, if you declare a variable with const, you must initialize it at the time of declaration, and you cannot assign it a value later in the code.

// Example of const variable declaration without initialization (this will throw an error)
