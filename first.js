//what is javascript
//javascript is a programming language that is used to create interactive and dynamic web pages. It allows developers to add functionality to their websites, such as form validation, animations, and user interactions. JavaScript can be used on both the client-side (in the browser) and the server-side (with Node.js). It is a versatile language that is widely used in web development.

// javcsript categories into two parts
//1. client-side javascript
//2. server-side javascript

//client-side javascript is executed in the browser and is used to create interactive web pages. It can manipulate the DOM (Document Object Model) to change the content and structure of a web page, handle user events, and make asynchronous requests to the server using AJAX (Asynchronous JavaScript and XML).

//server-side javascript is executed on the server and is used to create web applications and APIs. It can handle HTTP requests, interact with databases, and perform server-side logic. Node.js is a popular runtime environment for server-side JavaScript development.

//javascript is a versatile language that can be used for a wide range of applications, from simple web page enhancements to complex web applications and server-side development. It is an essential skill for web developers and is widely supported by all modern web browsers.


